let projects = [];

// Load projects from codebase + localStorage
function initProjects() {
    // 1. Get default projects directly from codebase
    const baseProjects = [...defaultProjects];
    
    // 2. Load custom projects added via Dev Controls
    let customProjects = [];
    const storedCustom = localStorage.getItem('portfolio_custom_projects');
    if (storedCustom) {
        try {
            customProjects = JSON.parse(storedCustom);
        } catch (e) {
            console.error("Error parsing custom projects", e);
        }
    }
    
    // Deduplicate: If a custom project has been permanently added to defaultProjects in the code,
    // remove it from customProjects in localStorage so it doesn't duplicate.
    const originalCustomLength = customProjects.length;
    customProjects = customProjects.filter(cp => !baseProjects.some(bp => bp.title === cp.title));
    if (customProjects.length !== originalCustomLength) {
        localStorage.setItem('portfolio_custom_projects', JSON.stringify(customProjects));
    }
    
    // 3. Load list of deleted default project titles
    let deletedDefaultTitles = [];
    const storedDeleted = localStorage.getItem('portfolio_deleted_defaults');
    if (storedDeleted) {
        try {
            deletedDefaultTitles = JSON.parse(storedDeleted);
        } catch (e) {
            console.error("Error parsing deleted defaults", e);
        }
    }
    
    // Filter out deleted defaults, then combine with custom projects
    projects = [
        ...baseProjects.filter(p => !deletedDefaultTitles.includes(p.title)),
        ...customProjects
    ];
}

