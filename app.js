// Delete Project Handler
function deleteProject(index) {
    const projectToDelete = projects[index];
    if (!projectToDelete) return;
    
    if (confirm(`Are you sure you want to remove the system project "${projectToDelete.title}"?`)) {
        // Check if it's a default project
        const isDefault = defaultProjects.some(p => p.title === projectToDelete.title);
        
        if (isDefault) {
            // Save to deleted defaults
            let deletedDefaultTitles = [];
            const storedDeleted = localStorage.getItem('portfolio_deleted_defaults');
            if (storedDeleted) {
                try { deletedDefaultTitles = JSON.parse(storedDeleted); } catch(e){}
            }
            if (!deletedDefaultTitles.includes(projectToDelete.title)) {
                deletedDefaultTitles.push(projectToDelete.title);
            }
            localStorage.setItem('portfolio_deleted_defaults', JSON.stringify(deletedDefaultTitles));
        } else {
            // Remove from custom projects list
            let customProjects = [];
            const storedCustom = localStorage.getItem('portfolio_custom_projects');
            if (storedCustom) {
                try { customProjects = JSON.parse(storedCustom); } catch(e){}
            }
            customProjects = customProjects.filter(p => p.title !== projectToDelete.title);
            localStorage.setItem('portfolio_custom_projects', JSON.stringify(customProjects));
        }
        
        // Re-initialize and render
        initProjects();
        renderProjects(getActiveFilter());
        renderDevProjectsList();
    }
}

