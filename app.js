// DYNAMIC PATH RESOLUTION HELPERS
// ----------------------------------------------------
function resolveImagePath(path) {
    if (!path) return '';
    let cleanPath = path.trim().replace(/\\/g, '/');
    
    // Auto-encode spaces in filename so standard HTML parses it correctly
    cleanPath = cleanPath.split('/').map(segment => encodeURIComponent(segment)).join('/');
    // Restore protocol and slash encodings
    cleanPath = cleanPath.replace(/http%3A%2F%2F/g, 'http://')
                         .replace(/https%3A%2F%2F/g, 'https://')
                         .replace(/%2F/g, '/');

    // If it contains the project workspace root or 'public/' folder segment
    if (cleanPath.includes('public/')) {
        cleanPath = cleanPath.substring(cleanPath.indexOf('public/') + 7); // Keep everything after 'public/'
    }
    
    // Ensure it starts with './' if it is a local relative asset
    if (cleanPath && !cleanPath.startsWith('/') && !cleanPath.startsWith('./') && !cleanPath.startsWith('http://') && !cleanPath.startsWith('https://') && !cleanPath.startsWith('data:')) {
        cleanPath = './' + cleanPath;
    }
    
    // Convert leading absolute slash to relative './' to support GitHub Pages subpaths
    if (cleanPath.startsWith('/')) {
        cleanPath = '.' + cleanPath;
    }
    
    return cleanPath;
}

// ----------------------------------------------------
// DATA SECURITY ENCODING
// ----------------------------------------------------
function escapeHTML(str) {
    if (!str) return '';
    return str
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
}

